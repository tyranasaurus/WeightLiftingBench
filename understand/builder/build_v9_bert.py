"""v9 BERT: rebalanced options (no two options from the same task cluster) + an encoder-only variant.

usage: python3 -I build_v9_bert.py <work dir>
Reads  <work>/out/wsu-reading-v8/tasks
Writes <work>/out/wsu-reading-v9/tasks        (v8 with the 17 BERT tasks' options rebuilt)
       <work>/out/wsu-bert-encoder-v1/tasks   (the 17 BERT tasks, rebalanced options, word vectors + vocab removed)
       <work>/out/v9_bert_build.json
"""
import json, re, shutil, sys
from collections import Counter
from pathlib import Path
import numpy as np

W = Path(sys.argv[1])
V8 = W / "out/wsu-reading-v8/tasks"
OUT9, OUTE = W / "out/wsu-reading-v9/tasks", W / "out/wsu-bert-encoder-v1/tasks"
LET = "ABCD"

# canonical descriptions (same strings as build_reading.D), only the 16 datasets that are v8 tasks
D = {
    "sms": "SMS spam: is a mobile text message spam",
    "enron": "Email spam: is an email (Enron corpus) spam",
    "fakenews": "Fake news: is a (US politics) news article fake or real",
    "toxicity": "Toxicity: is a user comment toxic",
    "injection": "Prompt injection: is a prompt sent to an LLM an injection attack",
    "sst2": "Sentiment (SST-2): is a single movie-review sentence positive or negative",
    "question": "Question focus: is a question about a document generic (e.g. asks for a summary) or about specific content",
    "mrpc": "MRPC: are two news sentences paraphrases of each other",
    "qqp": "QQP: are two Quora questions duplicates",
    "qnli": "QNLI: does a sentence contain the answer to a question",
    "mnli": "MNLI: does a premise entail, contradict or say nothing about a hypothesis",
    "stsb": "STS-B: how similar in meaning are two sentences, scored 0 to 5",
    "imdb": "Sentiment (IMDB): is a full-length IMDb movie review positive or negative",
    "amazon": "Sentiment (Amazon product reviews): is an Amazon product review positive or negative",
    "aitext_kaggle": "AI-text detection (Kaggle \"AI vs Human Text\" essays): was an essay written by a person or generated by an AI model",
    "aitext_autext": "AI-text detection (AuTexTification 2023 shared task, English, short texts from several domains): was a text written by a person or generated by a language model",
}
# near-sibling clusters: a question never offers two options from one cluster
CLUSTER = {"sms": "spam", "enron": "spam", "sst2": "sentiment", "imdb": "sentiment", "amazon": "sentiment",
           "aitext_kaggle": "aitext", "aitext_autext": "aitext",
           "mrpc": "pair", "qqp": "pair", "stsb": "pair", "mnli": "pair", "qnli": "pair"}
cl = lambda k: CLUSTER.get(k, k)
BY_TEXT = {v: k for k, v in D.items()}

ENC_OLD = "The pooler and the classification head were removed, so the network has no output layer; the embeddings, vocabulary and both encoder layers are included."
ENC_NEW = ("The pooler and the classification head were removed, so the network has no output layer. The word-embedding table "
           "and the vocabulary were also removed: you get the position and token-type embeddings, the embedding LayerNorm and "
           "both encoder layers. The description below is the full model; without the word embeddings it cannot be run on real "
           "text, so work from the remaining weights.")
VOCAB_OLD = re.compile(r"`vocab` \(strings\) gives the token of each id; lowercase and strip accents,\nsplit on whitespace and punctuation, then greedy longest-match WordPiece with `##` continuation pieces.")
VOCAB_NEW = "Text is tokenised with BERT's uncased WordPiece tokenizer (the vocabulary is not provided)."
DROP = ("embeddings.word_embeddings.weight", "vocab")


def options_block(opts):
    return "\n".join(f"{LET[i]}) {o}" for i, o in enumerate(opts))


def set_answer(d: Path, letter: str, text: str):
    full = f"{letter}) {text}"
    (d / "tests/expected.json").write_text(json.dumps({"accepted": [text, letter, full]}, indent=2))
    sv = (d / "solution/solve.sh").read_text(); sv, n = re.subn(r"ANSWER: .*", lambda m: "ANSWER: " + full, sv); assert n == 1
    (d / "solution/solve.sh").write_text(sv)


def main():
    for o in (OUT9, OUTE):
        shutil.rmtree(o, ignore_errors=True); o.mkdir(parents=True)
    bert = []
    for d in sorted(V8.iterdir()):
        shutil.copytree(d, OUT9 / d.name)
        ins = (d / "instruction.md").read_text()
        if "A small BERT encoder" in ins:
            ans = json.loads((d / "tests/expected.json").read_text())["accepted"][0]
            bert.append((d.name, BY_TEXT[ans]))
    assert len(bert) == 17, len(bert)
    keys = sorted(D)
    rng = np.random.default_rng(9009)
    # balanced letters (A5 B4 C4 D4) and balanced distractor use: greedily pick the least-used eligible distractor
    letters = [LET[i % 4] for i in range(len(bert))]; rng.shuffle(letters)
    use = Counter()
    report = []
    order = list(range(len(bert))); rng.shuffle(order)
    plan = {}
    for i in order:
        tid, key = bert[i]
        chosen, seen = [], {cl(key)}
        cands = [k for k in keys if k != key]
        rng.shuffle(cands)
        for _ in range(3):
            ok = [k for k in cands if cl(k) not in seen and k not in chosen]
            k = min(ok, key=lambda k: use[k])  # stable after shuffle: random among least-used
            chosen.append(k); seen.add(cl(k)); use[k] += 1
        L = letters[i]
        opts = [D[k] for k in chosen]; opts.insert(LET.index(L), D[key])
        assert len({cl(BY_TEXT[o]) for o in opts}) == 4
        plan[tid] = (key, L, opts)
    for tid, (key, L, opts) in sorted(plan.items()):
        d9 = OUT9 / tid
        ins = (d9 / "instruction.md").read_text()
        ins, n = re.subn(r"(Exactly one of these options is correct:\n)(?:[A-D]\) .*\n){4}", lambda m: m.group(1) + options_block(opts) + "\n", ins)
        assert n == 1
        (d9 / "instruction.md").write_text(ins)
        set_answer(d9, L, D[key])
        # encoder-only copy
        de = OUTE / (tid + "-enc")
        shutil.copytree(d9, de)
        sd = dict(np.load(de / "environment/policy.npz", allow_pickle=False))
        for k in DROP: assert k in sd, k
        sd = {k: v for k, v in sd.items() if k not in DROP}
        np.savez(de / "environment/policy.npz", **sd)
        e = ins
        assert e.count(ENC_OLD) == 1; e = e.replace(ENC_OLD, ENC_NEW)
        e, n = VOCAB_OLD.subn(VOCAB_NEW, e); assert n == 1
        for k in DROP:
            e, n = re.subn(rf"- `{re.escape(k)}`: \([^)]*\)\n", "", e); assert n == 1, k
        assert "vocab`" not in e and "word_embeddings.weight`" not in e
        (de / "instruction.md").write_text(e)
        toml = (de / "task.toml").read_text(); toml, n = re.subn(r'name = "wsp/([^"]+)"', lambda m: f'name = "wsp/{m.group(1)}-enc"', toml, count=1)
        assert n == 1; (de / "task.toml").write_text(toml)
        report.append(dict(id=tid, key=key, letter=L, options=[BY_TEXT[o] for o in opts], enc_params=int(sum(v.size for v in sd.values() if v.dtype.kind == "f"))))
        print(tid, key, L, [BY_TEXT[o] for o in opts])
    json.dump(dict(tasks=report, distractor_use=dict(use), letters=dict(Counter(letters))), open(W / "out/v9_bert_build.json", "w"), indent=1)
    print("distractor use", sorted(use.values()), "letters", Counter(letters), "enc params", report[0]["enc_params"])


if __name__ == "__main__":
    main()
