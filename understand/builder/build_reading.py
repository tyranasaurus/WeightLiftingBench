SST2_MAP = json.loads((W / "dl/sst2_map.json").read_text())  # task suffix -> (repo, revision)
for suf, (repo, rev) in SST2_MAP.items():
    OURS[suf] = (OURS[suf][0], repo, rev, OURS[suf][3])
NEW = json.loads((W / "dl/new_bert.json").read_text())  # list of {key, repo, dir}

BERT_KEYS = ["embeddings.word_embeddings.weight", "embeddings.position_embeddings.weight", "embeddings.token_type_embeddings.weight",
             "embeddings.LayerNorm.weight", "embeddings.LayerNorm.bias"]
for l in range(2):
    e = f"encoder.layer.{l}."
    for m in ("attention.self.query", "attention.self.key", "attention.self.value", "attention.output.dense", "attention.output.LayerNorm",
              "intermediate.dense", "output.dense", "output.LayerNorm"):
        BERT_KEYS += [e + m + ".weight", e + m + ".bias"]

BERT_MODEL = """## Model
A small BERT encoder (2 layers, hidden 128, 2 attention heads of 64, feed-forward 512, GELU, post-LayerNorm,
uncased WordPiece vocabulary of 30,522 tokens) that was fine-tuned for one English sentence or sentence-pair
task. The pooler and the classification head were removed, so the network has no output layer; the embeddings, vocabulary and both encoder layers are included.

Input: token ids `[CLS] A [SEP]` or `[CLS] A [SEP] B [SEP]` (token type 0 for the first segment including its
[SEP], 1 for B), at most 512 positions. `vocab` (strings) gives the token of each id; lowercase and strip accents,
split on whitespace and punctuation, then greedy longest-match WordPiece with `##` continuation pieces.

Forward pass (HF BERT names, linear weights (out, in), LN eps 1e-12, exact erf GELU):
  h = LN(word_embeddings[ids] + position_embeddings[0..n-1] + token_type_embeddings[types], embeddings.LayerNorm)
  for layer l in 0, 1 (prefix encoder.layer.l):
      q, k, v = attention.self.{query,key,value}(h); per head softmax(q k^T / 8) v (no masking for one sequence)
      h = LN(h + attention.output.dense(concat heads), attention.output.LayerNorm)
      h = LN(h + output.dense(gelu(intermediate.dense(h))), output.LayerNorm)

## Task
Which task was this encoder fine-tuned on? Exactly one of these options is correct:
"""
BERT_TAIL = """Answer with the option text or its letter.

## Access
The weights are in `/app/policy.npz` (load with `np.load`), one array per tensor:
{tensors}
You have Python 3 and numpy. No training data, labels, other checkpoints or deep learning frameworks are available. The network only reaches your model API. Work from the weights.

## Output
Write your answer to `/app/out/answer.txt`, ending with a final line of the form `ANSWER: <letter>) <option text>`. Only that line is graded; nothing you print is read.

"""
PAINT = {
    "candy": ("1ddfaea3", "Candy, a colourful abstract painting of bold curving shapes"),
    "udnie": ("7f9f28fe", "Udnie by Francis Picabia, an early abstract cubist painting"),
    "rain_princess": ("8d68acad", "Rain Princess by Leonid Afremov, a palette-knife painting of a rainy evening street"),
    "mosaic": ("ca959fbd", "Mosaic, a tiled stained-glass mosaic"),
    "pointilism": ("808bdbcc", "Pointilism, a pointillist painting built from small separate dots of colour"),
}
DROP_STYLE = {"d946ab77", "562dfd6d"}  # starry_night, edtaonisl


def add_note(ins: str) -> str:
    assert ins.count("\n\nRules:") == 1
    out = ins.replace("\n\nRules:", "\n\n" + NOTE + "\n\nRules:", 1)
    return out


def rules_tail(ins: str) -> str:
    i = ins.index("Rules:"); return ins[i:]


def set_answer(d: Path, letter: str, text: str):
    full = f"{letter}) {text}"
    (d / "tests/expected.json").write_text(json.dumps({"accepted": [text, letter, full]}, indent=2))
    sv = (d / "solution/solve.sh").read_text(); sv, n = re.subn(r"ANSWER: .*", lambda m: "ANSWER: " + full, sv); assert n == 1
    (d / "solution/solve.sh").write_text(sv)


def set_options(ins: str, opts: list[str]) -> str:
    text = "\n".join(f"{LET[i]}) {o}" for i, o in enumerate(opts))
    ins, n = re.subn(r"(Exactly one of these options is correct:\n)(?:[A-D]\) .*\n){4}", lambda m: m.group(1) + text + "\n", ins)
    assert n == 1; return ins


def balanced_letters(n: int, rng) -> list[str]:
    base = [LET[i % 4] for i in range(n)]; rng.shuffle(base); return base


def main():
    for o in (OUT1, OUT2):
        shutil.rmtree(o, ignore_errors=True); o.mkdir(parents=True)
    rng_opts = np.random.default_rng(7007)
    tasks = []  # dicts: id, family, src dir, sd (dict), instruction, answer letter/text, extra
    v6 = sorted(p for p in V6.iterdir() if p.is_dir())
    vocab = None
    # --- atari + lora: unchanged options
    for d in v6:
        sd = dict(np.load(d / "environment/policy.npz", allow_pickle=False))
        if d.name.startswith("diagnose-atari"):
            fam = "atari"
        elif "L04.q.A" in sd:
            fam = "lora"
        elif "vocab" in sd:
            fam = "bert"
            vocab = sd["vocab"] if vocab is None else vocab
            assert np.array_equal(vocab, sd["vocab"])
        else:
            fam = "fast-style"
        tasks.append(dict(id=d.name, family=fam, src=d, sd=sd))
    # --- fast style: keep 5 paintings, rebuild options with balanced letters
    style = [t for t in tasks if t["family"] == "fast-style"]
    tasks = [t for t in tasks if not (t["family"] == "fast-style" and t["id"][-8:] in DROP_STYLE)]
    names = list(PAINT); letters = balanced_letters(len(names), rng_opts)
    by_suffix = {t["id"][-8:]: t for t in tasks}
    for name, L in zip(names, letters):
        t = by_suffix[PAINT[name][0]]
        others = [o for o in names if o != name]; rng_opts.shuffle(others); others = others[:3]
        opts = others[:]; opts.insert(LET.index(L), name)
        t["options"] = [PAINT[o][1] for o in opts]; t["letter"] = L; t["answer"] = PAINT[name][1]; t["key"] = name
    # --- BERT: our 14 + new items, one template
    bert = [t for t in tasks if t["family"] == "bert"]
    assert len(bert) == 14, len(bert)
    for t in bert:
        k, repo, rev, lic = OURS[t["id"][-8:]]
        t.update(key=k, repo=repo, revision=rev, licence=lic, origin="v6")
        t["sd"] = {kk: t["sd"][kk] for kk in BERT_KEYS} | {"vocab": t["sd"]["vocab"]}
    tmpl = bert[0]["src"]
    for item in NEW:
        sd, meta = hfload.load(W / item["dir"])
        keep = {k: sd[k] for k in BERT_KEYS}
        for k in BERT_KEYS:
            assert keep[k].shape == bert[0]["sd"][k].shape and keep[k].dtype == np.float32, k
        tid = "diagnose-public-checkpoint-mcq-" + hashlib.sha1(("wsu7-bert-" + item["repo"]).encode()).hexdigest()[:8]
        assert tid not in {t["id"] for t in tasks}
        t = dict(id=tid, family="bert", src=tmpl, sd=keep | {"vocab": vocab}, key=item["key"], repo=item["repo"],
                 revision=meta["sha"], licence=meta["license"] or "not tagged", origin="new")
        tasks.append(t); bert.append(t)
    keys = sorted({t["key"] for t in bert})
    assert len(keys) == len(bert) - 2, "only the SST-2 triple may share a dataset"
    letters = balanced_letters(len(bert), rng_opts)
    for t, L in zip(sorted(bert, key=lambda t: t["id"]), letters):
        others = [D[k] for k in keys if k != t["key"]]; rng_opts.shuffle(others); others = others[:3]
        opts = others[:]; opts.insert(LET.index(L), D[t["key"]])
        t["options"] = opts; t["letter"] = L; t["answer"] = D[t["key"]]
    # --- round, permute, verify, write
    rules = rules_tail((V6 / "diagnose-atari-game-policy-0642485c/instruction.md").read_text())
    report, maxdiff, f16 = [], {}, {}
    for t in sorted(tasks, key=lambda t: t["id"]):
        fam = t["family"]; tid = t["id"]
        sd_r, st = wsu.round16(t["sd"])
        f16.setdefault(fam, dict(nonzero=0, flushed_to_zero=0, subnormal=0))
        for k in st: f16[fam][k] += st[k]
        pseed = wsu.seed_for("wsu-v7-perm", tid)
        perm, ver = wsu.FAMILY[fam]
        sd_p, info = perm(sd_r, np.random.default_rng(pseed))
        assert list(sd_p) == list(sd_r) and all(sd_p[k].shape == sd_r[k].shape for k in sd_r)
        assert any(not np.array_equal(sd_p[k], sd_r[k]) for k in sd_r if sd_r[k].dtype.kind == "f")
        for k in sd_r:  # permutation only moves values
            if sd_r[k].dtype.kind == "f":
                assert np.array_equal(np.sort(sd_p[k].ravel()), np.sort(sd_r[k].ravel())), k
        diff = ver(sd_r, sd_p, info, np.random.default_rng(pseed + 1))
        assert diff < 1e-6, (tid, diff)
        maxdiff[fam] = max(maxdiff.get(fam, 0.0), diff)
        d1 = OUT1 / tid
        shutil.copytree(t["src"], d1)
        np.savez(d1 / "environment/policy.npz", **sd_p)
        if fam == "bert":
            tens = "\n".join(f"- `{k}`: {tuple(sd_p[k].shape)}" for k in sd_p)
            ins = BERT_MODEL + "\n".join(f"{LET[i]}) {o}" for i, o in enumerate(t["options"])) + "\n" + BERT_TAIL.format(tensors=tens) + rules
            toml = (d1 / "task.toml").read_text(); toml = re.sub(r'name = "wsp/[^"]+"', f'name = "wsp/{tid}"', toml, count=1)
            (d1 / "task.toml").write_text(toml)
        else:
            ins = (t["src"] / "instruction.md").read_text()
            if fam == "fast-style":
                ins = set_options(ins, t["options"])
        ins = add_note(ins)
        (d1 / "instruction.md").write_text(ins)
        if "letter" in t:
            set_answer(d1, t["letter"], t["answer"])
        # dataset 2: shuffled values of dataset 1's npz
        sseed = wsu.seed_for("wsu-v7-shuffle", tid)
        sd_s = wsu.shuffle_values(sd_p, sseed)
        for k in sd_p:
            if sd_p[k].dtype.kind == "f":
                assert np.array_equal(np.sort(sd_s[k].ravel()), np.sort(sd_p[k].ravel())), k
            else:
                assert np.array_equal(sd_s[k], sd_p[k])
        d2 = OUT2 / (tid + "-shuf")
        shutil.copytree(d1, d2)
        np.savez(d2 / "environment/policy.npz", **sd_s)
        toml = (d2 / "task.toml").read_text(); toml, n = re.subn(r'name = "wsp/([^"]+)"', lambda m: f'name = "wsp/{m.group(1)}-shuf"', toml, count=1)
        assert n == 1; (d2 / "task.toml").write_text(toml)
        exp = json.loads((d1 / "tests/expected.json").read_text())["accepted"]
        report.append(dict(id=tid, family=fam, perm_seed=pseed, shuffle_seed=sseed, max_rel_diff=diff,
                           answer=(f"{t['letter']}) {t['answer']}" if "letter" in t else exp[-1]),
                           options=t.get("options"), key=t.get("key"), repo=t.get("repo"), revision=t.get("revision"),
                           licence=t.get("licence"), origin=t.get("origin")))
        print(tid, fam, f"{diff:.1e}", flush=True)
    json.dump(dict(tasks=report, max_rel_diff=maxdiff, f16=f16, note=NOTE), open(W / "out/reading_build.json", "w"), indent=1)
    print(maxdiff, f16)


if __name__ == "__main__":
    main()
